import json, re
L = ["hi", "ta", "te", "ml", "kn", "ar"]
RANGE = {"hi": "ऀ-ॿ", "ta": "஀-௿", "te": "ఀ-౿", "ml": "ഀ-ൿ", "kn": "ಀ-೿", "ar": "؀-ۿ"}
tr = json.load(open("tr/tr.json"))
bad = []
for line in T.strip().splitlines():
    p = [x.strip() for x in line.split("|")]
    assert len(p) == 7, line
    w = p[0].lower()
    tr[w] = {l: p[i + 1] for i, l in enumerate(L)}
    for l in L:
        if not re.fullmatch(r"[%s\s\-/]+" % RANGE[l], tr[w][l]): bad.append((w, l, tr[w][l]))
assert not bad, bad
json.dump(tr, open("tr/tr.json", "w"), ensure_ascii=False, separators=(",", ":"))
src = open("lang_block.js").read().split("\n")
assert src[2].startswith("const TR=")
src[2] = "const TR=" + json.dumps(tr, ensure_ascii=False, separators=(",", ":")) + ";"
open("lang_block.js", "w").write("\n".join(src))
print("words", len(tr))
